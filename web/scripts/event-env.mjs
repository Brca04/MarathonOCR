#!/usr/bin/env node
/**
 * One codebase, one settings file per event.
 *
 *   events/<slug>.env   public settings for one race (name, date, colours,
 *                       logo, Supabase URL + publishable key). Committed.
 *
 * Pick the event with EVENT=<slug>, for example
 *
 *   EVENT=zagreb-2026 npm run build
 *   EVENT=zagreb-2026 npm run export:static
 *
 * Values already in the environment win, so a Cloudflare build variable or an
 * `export` in your shell still overrides the file. Secrets (the Supabase
 * service key, SESSION_SECRET, TURNSTILE_SECRET) never go in these files.
 *
 * As a script (it runs before every `next build` and `next dev`) it writes the
 * chosen event to .env.production.local and .env.development.local, which
 * Next.js reads during the build and the local preview. Without
 * EVENT it builds the default event (zagreb-2026).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import dotenv from 'dotenv';

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GENERATED = ['.env.production.local', '.env.development.local'].map((f) => path.join(WEB, f));
const MARK = '# generated by scripts/event-env.mjs';

export function eventFile(slug) {
  return path.join(WEB, 'events', `${slug}.env`);
}

/** Load events/<EVENT>.env into process.env without overriding what is set. */
export const DEFAULT_EVENT = 'zagreb-2026';

export function loadEvent(slug = process.env.EVENT || DEFAULT_EVENT) {
  if (!slug) return null;
  const file = eventFile(slug);
  if (!fs.existsSync(file)) {
    const known = fs.existsSync(path.join(WEB, 'events'))
      ? fs.readdirSync(path.join(WEB, 'events')).filter((f) => f.endsWith('.env')).map((f) => f.slice(0, -4))
      : [];
    throw new Error(`EVENT=${slug}: no file events/${slug}.env (known: ${known.join(', ') || 'none'})`);
  }
  const values = dotenv.parse(fs.readFileSync(file));
  for (const [k, v] of Object.entries(values)) {
    if (process.env[k] === undefined) process.env[k] = v;
  }
  return values;
}

// Run directly: write the event settings for `next build` and `next dev`.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const slug = process.env.EVENT || DEFAULT_EVENT;
  try {
    const values = loadEvent(slug);
    const lines = Object.entries(values).map(([k, v]) => `${k}=${JSON.stringify(v)}`);
    for (const f of GENERATED) fs.writeFileSync(f, `${MARK} for EVENT=${slug}\n${lines.join('\n')}\n`);
    console.log(`[event] building ${slug} (${Object.keys(values).length} settings from events/${slug}.env)`);
  } catch (e) {
    console.error(`[event] ${e.message}`);
    process.exit(1);
  }
}
